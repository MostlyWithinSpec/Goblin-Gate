package config

import (
	"encoding/base64"
	"fmt"
	"net/netip"
	"strings"
)

// Gateway is a next hop to the internet (task 049): a WAN interface's
// router, or a WireGuard client tunnel (a VPN provider). Every gateway gets
// its own routing table; goblind's monitor pings Monitor.IP through it.
type Gateway struct {
	Name string `json:"name"`
	// Interface is a WAN interface or VLAN, or a WireGuard client name.
	Interface string `json:"interface"`
	// Address is the router's IPv4 address, "dhcp" (learned on the
	// interface) or "" for a tunnel (point to point).
	Address string         `json:"address,omitempty"`
	Monitor GatewayMonitor `json:"monitor,omitzero"`
}

// GatewayMonitor is how goblind decides a gateway is up.
type GatewayMonitor struct {
	// IP is pinged through the gateway; "" = a public resolver picked per
	// gateway (1.1.1.1, 8.8.8.8, 9.9.9.9, ...). Each gateway needs its own.
	IP string `json:"ip,omitempty"`
	// Disabled keeps the gateway always up (no pings).
	Disabled bool `json:"disabled,omitempty"`
	// IntervalSeconds between pings (0 = 2).
	IntervalSeconds int `json:"interval_seconds,omitempty"`
	// LossPercent over the last 10 pings at or above which it is down (0 = 40).
	LossPercent int `json:"loss_percent,omitempty"`
	// LatencyMs average above which it is down (0 = 1000).
	LatencyMs int `json:"latency_ms,omitempty"`
}

// GatewayGroup spreads or fails over traffic between gateways: the lowest
// tier with a gateway up carries the traffic, shared by weight inside it.
type GatewayGroup struct {
	Name    string        `json:"name"`
	Members []GroupMember `json:"members"`
}

// GroupMember is one gateway of a group.
type GroupMember struct {
	Gateway string `json:"gateway"`
	Tier    int    `json:"tier,omitempty"`   // 1 = first choice (0 counts as 1)
	Weight  int    `json:"weight,omitempty"` // share within the tier (0 = 1)
}

// Route is a static route via a gateway (a gateway name, not a group).
type Route struct {
	Destination netip.Prefix `json:"destination"`
	Gateway     string       `json:"gateway"`
	Comment     string       `json:"comment,omitempty"`
}

// WireGuardClient is a tunnel to a VPN provider (Mullvad, Proton, ...)
// that works as a gateway (task 049). Its private key lives in
// WireGuardKeyDir as client-<name>.key, generated by goblind or pasted
// through the API; it is never part of the config.
type WireGuardClient struct {
	Name    string       `json:"name"` // device name: 1-15 of [a-z0-9_-]
	Enabled bool         `json:"enabled"`
	Address netip.Prefix `json:"address"` // the box's tunnel address from the provider, e.g. 10.64.12.34/32
	// PeerPublicKey, Endpoint ("host:port") and PresharedKey come from the
	// provider's config file.
	PeerPublicKey string `json:"peer_public_key"`
	Endpoint      string `json:"endpoint"`
	// AllowedIPs routed into the tunnel by policies (default 0.0.0.0/0).
	AllowedIPs []netip.Prefix `json:"allowed_ips,omitempty"`
	// DNS servers of the provider (informational: the box keeps its resolver).
	DNS       []netip.Addr `json:"dns,omitempty"`
	Keepalive int          `json:"keepalive,omitempty"` // seconds, 0 = 25
	MTU       int          `json:"mtu,omitempty"`
	// KillSwitch drops the traffic policies send to this tunnel while it is
	// down instead of letting it out through the WAN.
	KillSwitch bool `json:"kill_switch,omitempty"`
}

// ClientKeyName is the key file base name of a WireGuard client.
func ClientKeyName(name string) string { return "client-" + name }

// Monitor defaults.
const (
	DefaultMonitorInterval = 2
	DefaultMonitorLoss     = 40
	DefaultMonitorLatency  = 1000
	DefaultClientKeepalive = 25
)

// DefaultMonitorIPs are pinged when monitor.ip is empty: the n-th gateway
// without one gets the n-th address.
var DefaultMonitorIPs = []string{"1.1.1.1", "8.8.8.8", "9.9.9.9", "208.67.222.222", "1.0.0.1", "8.8.4.4", "149.112.112.112", "208.67.220.220"}

// MonitorIPs returns the address each gateway's monitor pings ("" when the
// monitor is off), filling empty ones from DefaultMonitorIPs.
func (c *Config) MonitorIPs() map[string]string {
	out := map[string]string{}
	used := map[string]bool{}
	for _, g := range c.Gateways {
		if g.Monitor.IP != "" {
			used[g.Monitor.IP] = true
		}
	}
	next := 0
	for _, g := range c.Gateways {
		switch {
		case g.Monitor.Disabled:
			out[g.Name] = ""
		case g.Monitor.IP != "":
			out[g.Name] = g.Monitor.IP
		default:
			for next < len(DefaultMonitorIPs) && used[DefaultMonitorIPs[next]] {
				next++
			}
			if next < len(DefaultMonitorIPs) {
				out[g.Name] = DefaultMonitorIPs[next]
				used[DefaultMonitorIPs[next]] = true
			}
		}
	}
	return out
}

// GatewayTarget reports whether name is a gateway or a gateway group.
func (c *Config) GatewayTarget(name string) (gateway, group bool) {
	for _, g := range c.Gateways {
		if g.Name == name {
			return true, false
		}
	}
	for _, g := range c.GatewayGroups {
		if g.Name == name {
			return false, true
		}
	}
	return false, false
}

func (v *validator) checkRouting() {
	c := v.cfg
	wan := map[string]bool{}
	for _, in := range c.Interfaces {
		if in.Role == "wan" {
			wan[in.Name] = true
		}
	}
	for _, vl := range c.VLANs {
		if r, _ := v.netifRole(vl.Name); r == "wan" {
			wan[vl.Name] = true
		}
	}
	clients := map[string]bool{}
	for i, w := range c.VPN.WireGuardClients {
		p := fmt.Sprintf("vpn.wireguard_clients[%d]", i)
		if !wgNameRe.MatchString(w.Name) {
			v.add(p+".name", "invalid device name %q: 1-15 of a-z, 0-9, _ and -", w.Name)
		}
		if clients[w.Name] {
			v.add(p+".name", "duplicate WireGuard client %q", w.Name)
		}
		clients[w.Name] = true
		for _, s := range c.VPN.WireGuard {
			if s.Name == w.Name {
				v.add(p+".name", "%q is already a WireGuard server", w.Name)
			}
		}
		if !w.Address.IsValid() || !w.Address.Addr().Is4() {
			v.add(p+".address", "want the IPv4 tunnel address from the provider, e.g. 10.64.0.2/32")
		}
		if !validWGKey(w.PeerPublicKey) {
			v.add(p+".peer_public_key", "want the provider's public key (base64, 32 bytes)")
		}
		if host, port, ok := strings.Cut(w.Endpoint, ":"); !ok || host == "" || port == "" {
			v.add(p+".endpoint", "want host:port, e.g. se-sto-wg-001.example.net:51820")
		}
		if w.MTU != 0 && (w.MTU < 1280 || w.MTU > 1500) {
			v.add(p+".mtu", "mtu %d out of range 1280-1500", w.MTU)
		}
	}
	gws := map[string]Gateway{}
	monitor := map[string]string{}
	for i, g := range c.Gateways {
		p := fmt.Sprintf("gateways[%d]", i)
		if !nameRe.MatchString(g.Name) {
			v.add(p+".name", "invalid name %q", g.Name)
		}
		if _, dup := gws[g.Name]; dup {
			v.add(p+".name", "duplicate gateway %q", g.Name)
		}
		gws[g.Name] = g
		switch {
		case clients[g.Interface]:
			if g.Address != "" {
				v.add(p+".address", "a WireGuard tunnel gateway has no address")
			}
		case wan[g.Interface]:
			if g.Address != "dhcp" {
				if a, err := netip.ParseAddr(g.Address); err != nil || !a.Is4() {
					v.add(p+".address", "want the router's IPv4 address or \"dhcp\"")
				}
			}
		default:
			v.add(p+".interface", "%q is not a WAN interface or WireGuard client", g.Interface)
		}
		if ip := g.Monitor.IP; ip != "" {
			if a, err := netip.ParseAddr(ip); err != nil || !a.Is4() {
				v.add(p+".monitor.ip", "want an IPv4 address")
			} else if other, dup := monitor[ip]; dup {
				v.add(p+".monitor.ip", "%s is already monitored through %s: each gateway needs its own address", ip, other)
			} else {
				monitor[ip] = g.Name
			}
		}
		m := g.Monitor
		if m.IntervalSeconds < 0 || m.IntervalSeconds > 60 || m.LossPercent < 0 || m.LossPercent > 100 || m.LatencyMs < 0 {
			v.add(p+".monitor", "interval 1-60 s, loss 0-100 %%, latency >= 0 ms")
		}
	}
	if len(c.Gateways) > len(DefaultMonitorIPs)+len(monitor) {
		v.add("gateways", "too many gateways without a monitor ip")
	}
	// every enabled WAN needs a gateway once gateways are configured: goblind
	// then owns the default route
	if len(c.Gateways) > 0 {
		has := map[string]bool{}
		for _, g := range c.Gateways {
			has[g.Interface] = true
		}
		for i, in := range c.Interfaces {
			if in.Role == "wan" && in.Enabled && in.Mode != "none" && !has[in.Name] {
				v.add(fmt.Sprintf("interfaces[%d]", i), "WAN %q has no gateway: add one (gateways), or none at all for a single WAN", in.Name)
			}
		}
	}
	groups := map[string]bool{}
	for i, gg := range c.GatewayGroups {
		p := fmt.Sprintf("gateway_groups[%d]", i)
		if !nameRe.MatchString(gg.Name) {
			v.add(p+".name", "invalid name %q", gg.Name)
		}
		if _, clash := gws[gg.Name]; clash || groups[gg.Name] {
			v.add(p+".name", "%q is already a gateway or group", gg.Name)
		}
		groups[gg.Name] = true
		if len(gg.Members) == 0 {
			v.add(p+".members", "a group needs at least one gateway")
		}
		seen := map[string]bool{}
		for j, m := range gg.Members {
			mp := fmt.Sprintf("%s.members[%d]", p, j)
			if _, ok := gws[m.Gateway]; !ok {
				v.add(mp+".gateway", "unknown gateway %q", m.Gateway)
			}
			if seen[m.Gateway] {
				v.add(mp+".gateway", "%q is listed twice", m.Gateway)
			}
			seen[m.Gateway] = true
			if m.Tier < 0 || m.Tier > 5 || m.Weight < 0 || m.Weight > 100 {
				v.add(mp, "tier 1-5, weight 1-100")
			}
		}
	}
	target := func(p, name string) {
		if name == "" {
			return
		}
		if _, ok := gws[name]; !ok && !groups[name] {
			v.add(p, "unknown gateway or gateway group %q", name)
		}
	}
	target("default_gateway", c.DefaultGateway)
	if c.DefaultGateway != "" && len(c.Gateways) == 0 {
		v.add("default_gateway", "no gateways are configured")
	}
	// a routed policy's dst_intf must let the routed traffic out: the
	// forward check sees the gateway's interface as the egress
	gwIface := map[string][]string{}
	for _, g := range c.Gateways {
		gwIface[g.Name] = []string{g.Interface}
	}
	for _, gg := range c.GatewayGroups {
		for _, m := range gg.Members {
			gwIface[gg.Name] = append(gwIface[gg.Name], gwIface[m.Gateway]...)
		}
	}
	for i, pol := range c.Policies {
		p := fmt.Sprintf("policies[%d].gateway", i)
		target(p, pol.Gateway)
		if pol.Gateway == "" || pol.Action != "accept" {
			continue
		}
		dst := toSet(pol.DstIntf)
		if dst["all"] || dst["any"] {
			continue
		}
		for _, in := range gwIface[pol.Gateway] {
			if !dst[in] {
				v.add(p, "the policy sends traffic out through %q but its dst_intf does not include it: add it or use \"all\"", in)
			}
		}
	}
	perIface := map[string]string{}
	for i, g := range c.Gateways {
		if other, dup := perIface[g.Interface]; dup {
			v.add(fmt.Sprintf("gateways[%d].interface", i), "%q already has gateway %q: one gateway per interface", g.Interface, other)
		}
		perIface[g.Interface] = g.Name
	}
	for i, r := range c.Routes {
		p := fmt.Sprintf("routes[%d]", i)
		if !r.Destination.IsValid() || !r.Destination.Addr().Is4() {
			v.add(p+".destination", "want an IPv4 subnet")
		}
		if _, ok := gws[r.Gateway]; !ok {
			v.add(p+".gateway", "unknown gateway %q (static routes take a gateway, not a group)", r.Gateway)
		}
	}
}

func validWGKey(s string) bool {
	k, err := base64.StdEncoding.DecodeString(s)
	return err == nil && len(k) == 32
}
