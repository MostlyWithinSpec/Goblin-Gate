// Package ips turns the shared Suricata rule download into one rule set per
// IPS profile (task 031) and keeps the per-profile Suricata instances fed.
package ips

import (
	"bufio"
	"fmt"
	"io"
	"regexp"
	"strconv"
	"strings"

	"github.com/networkgoblinlabs/goblin-gate/internal/config"
)

// DefaultBlockSeverity is used when a profile leaves block_severity at 0.
const DefaultBlockSeverity = 2

// DefaultExcluded are the ET categories left out when a profile lists no
// categories: noisy, informational or not about attacks. SURICATA (the
// engine's own decoder and stream events) is also left out by default and
// is never turned into drop rules.
var DefaultExcluded = map[string]bool{"POLICY": true, "INFO": true, "GAMES": true, "CHAT": true, "HUNTING": true, "SURICATA": true}

// ParseClassifications reads Suricata's classification.config
// ("config classification: shortname,description,priority") into
// shortname -> priority.
func ParseClassifications(r io.Reader) (map[string]int, error) {
	out := map[string]int{}
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		rest, ok := strings.CutPrefix(line, "config classification:")
		if !ok {
			continue
		}
		parts := strings.Split(rest, ",")
		if len(parts) < 3 {
			continue
		}
		prio, err := strconv.Atoi(strings.TrimSpace(parts[len(parts)-1]))
		if err != nil {
			continue
		}
		out[strings.TrimSpace(parts[0])] = prio
	}
	return out, sc.Err()
}

// Stats counts what ProfileRules wrote.
type Stats struct {
	Drop, Alert, Skipped int
}

var (
	msgRe      = regexp.MustCompile(`msg\s*:\s*"([^"]*)"`)
	priorityRe = regexp.MustCompile(`(?:^|;)\s*priority\s*:\s*(\d+)\s*;`)
	classRe    = regexp.MustCompile(`(?:^|;)\s*classtype\s*:\s*([^;\s]+)\s*;`)
	noalertRe  = regexp.MustCompile(`(?:^|;)\s*(?:noalert|flowbits\s*:\s*noalert)\s*;`)
)

// Category returns the ET category of a rule message ("ET MALWARE x" ->
// MALWARE), "SURICATA" for the engine's own rules and "" otherwise.
func Category(msg string) string {
	f := strings.Fields(msg)
	switch {
	case len(f) >= 2 && (f[0] == "ET" || f[0] == "ETPRO"):
		return strings.ToUpper(f[1])
	case len(f) >= 1 && f[0] == "SURICATA":
		return "SURICATA"
	}
	return ""
}

// ProfileRules copies the enabled rules from src that the profile selects,
// rewriting their action: detect mode only alerts; prevent mode drops rules
// whose severity (priority keyword, else the classtype's priority, else 3)
// is at or above block_severity (1 = highest) and alerts on the rest.
// Rules that never alert (flowbits setters with noalert) keep alert, and
// pass rules are copied unchanged.
func ProfileRules(w io.Writer, src io.Reader, p config.IPSProfile, classes map[string]int) (Stats, error) {
	var st Stats
	block := p.BlockSeverity
	if block == 0 {
		block = DefaultBlockSeverity
	}
	want := map[string]bool{}
	for _, c := range p.Categories {
		want[strings.ToUpper(c)] = true
	}
	bw := bufio.NewWriter(w)
	fmt.Fprintf(bw, "# Generated by Goblin Gate for IPS profile %q (mode %s, block severity <= %d) - do not edit\n", p.Name, modeOf(p), block)
	sc := bufio.NewScanner(src)
	sc.Buffer(make([]byte, 64<<10), 1<<20)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || line[0] == '#' {
			continue
		}
		action, rest, ok := strings.Cut(line, " ")
		if !ok {
			st.Skipped++
			continue
		}
		var msg string
		if m := msgRe.FindStringSubmatch(rest); m != nil {
			msg = m[1]
		}
		cat := Category(msg)
		if len(want) > 0 {
			if !want[cat] {
				st.Skipped++
				continue
			}
		} else if DefaultExcluded[cat] {
			st.Skipped++
			continue
		}
		switch action {
		case "pass":
			bw.WriteString(line + "\n")
			continue
		case "alert", "drop", "reject", "rejectsrc", "rejectdst", "rejectboth":
		default:
			st.Skipped++
			continue
		}
		newAction := "alert"
		if modeOf(p) == "prevent" && cat != "SURICATA" && !noalertRe.MatchString(rest) && severity(rest, classes) <= block {
			newAction = "drop"
		}
		if newAction == "drop" {
			st.Drop++
		} else {
			st.Alert++
		}
		bw.WriteString(newAction + " " + rest + "\n")
	}
	if err := sc.Err(); err != nil {
		return st, fmt.Errorf("ips: read rules: %w", err)
	}
	return st, bw.Flush()
}

func modeOf(p config.IPSProfile) string {
	if p.Mode == "detect" {
		return "detect"
	}
	return "prevent"
}

func severity(rule string, classes map[string]int) int {
	if m := priorityRe.FindStringSubmatch(rule); m != nil {
		if n, err := strconv.Atoi(m[1]); err == nil {
			return n
		}
	}
	if m := classRe.FindStringSubmatch(rule); m != nil {
		if n, ok := classes[m[1]]; ok {
			return n
		}
	}
	return 3
}
