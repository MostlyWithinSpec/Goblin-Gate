// Package upnp renders miniupnpd's configuration (task 059): UPnP IGD,
// NAT-PMP and PCP for the LAN-side interfaces in upnp.interfaces, with the
// first enabled WAN as the external interface.
//
// miniupnpd (Debian's miniupnpd-nftables) writes its port mappings into
// chains that the Goblin ruleset owns (internal/render/nft): forward accepts
// into "upnp_forward" in table inet goblin, DNAT into "upnp_dnat" (and
// "upnp_snat") in table inet goblin_upnp. Both tables are recreated on every
// commit, so the applier restarts goblin-miniupnpd after loading the
// ruleset and miniupnpd re-adds the mappings from its lease file.
package upnp

import (
	"crypto/sha256"
	"fmt"
	"net/netip"
	"strings"

	"github.com/networkgoblinlabs/goblin-gate/internal/config"
	"github.com/networkgoblinlabs/goblin-gate/internal/render"
)

// Paths and fixed settings shared with the nft renderer, the applier and the API.
const (
	Dir        = "/etc/goblingate/upnp/"
	ConfPath   = Dir + "miniupnpd.conf"
	LeaseFile  = "/var/lib/goblingate/upnp/leases"
	Unit       = "goblin-miniupnpd.service"
	HTTPPort   = 2189 // UPnP device description/control (SSDP announces it)
	SSDPPort   = 1900
	STUNHost   = "stun.l.google.com" // upnp.stun
	STUNPort   = 19302
	NATPMPPort = 5351 // NAT-PMP and PCP

	FilterTable  = "goblin"      // inet; must match nft.FilterTable
	NATTable     = "goblin_upnp" // inet, owned by the nft renderer
	ForwardChain = "upnp_forward"
	DNATChain    = "upnp_dnat"
	SNATChain    = "upnp_snat"
)

// Renderer implements commit.Renderer.
type Renderer struct{}

// Name returns "upnp".
func (Renderer) Name() string { return "upnp" }

// Render returns miniupnpd.conf when UPnP is enabled, nothing otherwise (the
// applier then stops the service).
func (Renderer) Render(cfg *config.Config) (map[string][]byte, error) {
	u := cfg.UPnP
	if !u.Enabled {
		return map[string][]byte{}, nil
	}
	devs := render.Devices(cfg)
	ext := ""
	for _, i := range cfg.Interfaces {
		if i.Enabled && i.Role == "wan" {
			ext = devs[i.Name]
			break
		}
	}
	if ext == "" {
		return nil, fmt.Errorf("render upnp: no enabled WAN interface")
	}
	var b strings.Builder
	b.WriteString("# Generated by Goblin Gate — do not edit\n")
	fmt.Fprintf(&b, "ext_ifname=%s\n", ext)
	for _, name := range u.Interfaces {
		dev, ok := devs[name]
		if !ok {
			return nil, fmt.Errorf("render upnp: unknown interface %q", name)
		}
		fmt.Fprintf(&b, "listening_ip=%s\n", dev)
	}
	fmt.Fprintf(&b, "http_port=%d\n", HTTPPort)
	b.WriteString("enable_upnp=yes\n")
	fmt.Fprintf(&b, "enable_natpmp=%s\n", yesNo(u.NATPMPOn()))
	fmt.Fprintf(&b, "secure_mode=%s\n", yesNo(u.SecureOn()))
	b.WriteString("system_uptime=yes\n")
	fmt.Fprintf(&b, "lease_file=%s\n", LeaseFile)
	maxLease := u.MaxLease
	if maxLease == 0 {
		maxLease = config.DefaultUPnPMaxLease
	}
	fmt.Fprintf(&b, "max_lifetime=%d\n", maxLease)
	if u.STUN {
		fmt.Fprintf(&b, "ext_perform_stun=yes\next_stun_host=%s\next_stun_port=%d\n", STUNHost, STUNPort)
	}
	b.WriteString("clean_ruleset_interval=600\n")
	fmt.Fprintf(&b, "upnp_table_name=%s\nupnp_nat_table_name=%s\n", FilterTable, NATTable)
	fmt.Fprintf(&b, "upnp_forward_chain=%s\nupnp_nat_chain=%s\nupnp_nat_postrouting_chain=%s\n", ForwardChain, DNATChain, SNATChain)
	fmt.Fprintf(&b, "friendly_name=Goblin Gate %s\n", cfg.System.Hostname)
	fmt.Fprintf(&b, "uuid=%s\n", uuid(cfg.System.Hostname))

	// Permissions: first match wins; everything else is denied.
	if len(u.Allow) == 0 { // every client on the served interfaces
		for _, name := range u.Interfaces {
			p, ok := ifaceSubnet(cfg, name)
			if !ok {
				return nil, fmt.Errorf("render upnp: interface %q has no IPv4 address", name)
			}
			fmt.Fprintf(&b, "allow 1024-65535 %s 1024-65535\n", p)
		}
	}
	for _, a := range u.Allow {
		p, err := cfg.UPnPAllowPrefix(a.Address)
		if err != nil {
			return nil, fmt.Errorf("render upnp: allow: %w", err)
		}
		fmt.Fprintf(&b, "allow %s %s %s\n", a.Ports, p, a.Ports)
	}
	b.WriteString("deny 0-65535 0.0.0.0/0 0-65535\n")
	return map[string][]byte{ConfPath: []byte(b.String())}, nil
}

// ifaceSubnet returns the IPv4 subnet of an interface or VLAN.
func ifaceSubnet(cfg *config.Config, name string) (netip.Prefix, bool) {
	for _, i := range cfg.Interfaces {
		if i.Name == name && i.Address != nil {
			return i.Address.Masked(), true
		}
	}
	for _, v := range cfg.VLANs {
		if v.Name == name && v.Address != nil {
			return v.Address.Masked(), true
		}
	}
	return netip.Prefix{}, false
}

func yesNo(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}

// uuid derives a stable device UUID from the hostname, so clients keep
// recognising the gateway across restarts.
func uuid(host string) string {
	h := sha256.Sum256([]byte("goblin-gate-upnp:" + host))
	h[6] = h[6]&0x0f | 0x50 // version 5-style
	h[8] = h[8]&0x3f | 0x80 // RFC 4122 variant
	return fmt.Sprintf("%x-%x-%x-%x-%x", h[0:4], h[4:6], h[6:8], h[8:10], h[10:16])
}
