// Package radius renders FreeRADIUS's configuration: one self-contained
// radiusd.conf that answers the configured switches and access points and
// asks goblind (rlm_rest, on loopback) for every decision. goblind knows the
// device inventory, the users and the VLANs; FreeRADIUS does the protocol:
// RADIUS, EAP-PEAP with MSCHAPv2 and EAP-TLS.
package radius

import (
	"fmt"
	"slices"
	"strings"

	"github.com/networkgoblinlabs/goblin-gate/internal/config"
)

// Paths. goblin-radius.service copies Dir and the certificates into RunDir
// for the freerad user and runs FreeRADIUS from there.
const (
	Dir      = "/etc/goblingate/radius/"
	ConfPath = Dir + "radiusd.conf"
	DictPath = Dir + "dictionary"
	// CertDir holds the server certificate goblind issues from the internal
	// CA (server.pem, server.key) and the CA's root (ca.pem), for 802.1X.
	CertDir = Dir + "certs/"
	RunDir  = "/run/goblin-radius"
	Unit    = "goblin-radius.service"
	// HookAddr is goblind's endpoint for FreeRADIUS (loopback only).
	HookAddr = "127.0.0.1:18122"
	// HookUser is the basic-auth user name; the password is Renderer.Token.
	HookUser = "freeradius"
)

// Certs is the 802.1X server certificate and key and the CA root (PEM).
type Certs struct {
	Cert, Key, CA []byte
}

// Renderer writes the configuration while RADIUS is active. Token returns
// the box's hook password (box state in the data dir, not config); Certs
// returns the server certificate for 802.1X (issued once, then reused).
type Renderer struct {
	Token func() (string, error)
	Certs func(cfg *config.Config) (Certs, error)
}

func (Renderer) Name() string { return "radius" }

func (r Renderer) Render(cfg *config.Config) (map[string][]byte, error) {
	if !cfg.RADIUSActive() {
		return map[string][]byte{}, nil
	}
	if r.Token == nil {
		return nil, fmt.Errorf("render radius: no hook token")
	}
	token, err := r.Token()
	if err != nil || token == "" {
		return nil, fmt.Errorf("render radius: hook token: %v", err)
	}
	conf, err := Build(cfg, token)
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{
		ConfPath: conf,
		DictPath: []byte("# Generated by Goblin Gate — do not edit (local dictionary: empty)\n"),
	}
	if cfg.RADIUS.Dot1X {
		if r.Certs == nil {
			return nil, fmt.Errorf("render radius: no server certificate")
		}
		c, err := r.Certs(cfg)
		if err != nil {
			return nil, fmt.Errorf("render radius: %w", err)
		}
		out[CertDir+"server.pem"] = c.Cert
		out[CertDir+"server.key"] = c.Key
		out[CertDir+"ca.pem"] = c.CA
	}
	return out, nil
}

// Build renders radiusd.conf.
func Build(cfg *config.Config, token string) ([]byte, error) {
	rc := cfg.RADIUS
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	w("# Generated by Goblin Gate — do not edit")
	w(`prefix = /usr
exec_prefix = /usr
sysconfdir = /etc
localstatedir = /var
sbindir = /usr/sbin
logdir = /var/log/freeradius
raddbdir = %s
radacctdir = ${logdir}/radacct
name = radiusd
confdir = ${raddbdir}
modconfdir = ${confdir}/mods-config
certdir = ${confdir}/certs
cadir = ${confdir}/certs
run_dir = ${raddbdir}
db_dir = ${raddbdir}
libdir = /usr/lib/freeradius
pidfile = ${run_dir}/${name}.pid
correct_escapes = true
max_request_time = 30
cleanup_delay = 5
max_requests = 16384
hostname_lookups = no
proxy_requests = no

log {
	destination = stdout
	colourise = no
	stripped_names = no
	auth = no
}

security {
	allow_core_dumps = no
	max_attributes = 200
	reject_delay = 1
	status_server = yes
}

thread pool {
	start_servers = 4
	max_servers = 32
	min_spare_servers = 2
	max_spare_servers = 8
	max_requests_per_server = 0
	auto_limit_acct = no
}
`, RunDir)

	// the switches and access points
	clients := slices.Clone(rc.Clients)
	slices.SortFunc(clients, func(a, b config.RADIUSClient) int { return strings.Compare(a.Name, b.Name) })
	for _, c := range clients {
		p, ok := c.Prefix()
		if !ok || !secretOK(c.Secret) {
			return nil, fmt.Errorf("render radius: client %q: bad address or secret", c.Name)
		}
		key := "ipaddr"
		if p.Addr().Is6() {
			key = "ipv6addr"
		}
		w("client %s {", c.Name)
		w("\t%s = %s", key, p)
		w("\tsecret = \"%s\"", c.Secret)
		w("\tshortname = %s", c.Name)
		w("\trequire_message_authenticator = no")
		w("}")
		w("")
	}

	// rlm_rest instances: one per question goblind answers. 401 = reject,
	// 404 = not found, 2xx with attributes = updated.
	rest := func(instance, section, path string) {
		w("\trest %s {", instance)
		w("\t\tconnect_uri = \"http://%s/radius\"", HookAddr)
		w("\t\tconnect_timeout = 2.0")
		w("\t\t%s {", section)
		w("\t\t\turi = \"${..connect_uri}/%s\"", path)
		w("\t\t\tmethod = 'post'")
		w("\t\t\tbody = 'json'")
		w("\t\t\tauth = 'basic'")
		w("\t\t\tusername = \"%s\"", HookUser)
		w("\t\t\tpassword = \"%s\"", token)
		w("\t\t\trequire_auth = yes")
		w("\t\t\ttimeout = 4")
		w("\t\t}")
		w("\t\tpool {")
		w("\t\t\tstart = 0")
		w("\t\t\tmin = 0")
		w("\t\t\tmax = 32")
		w("\t\t\tspare = 4")
		w("\t\t\tuses = 0")
		w("\t\t\tretry_delay = 5")
		w("\t\t\tlifetime = 0")
		w("\t\t\tidle_timeout = 60")
		w("\t\t}")
		w("\t}")
	}
	w("modules {")
	w("\talways reject {\n\t\trcode = reject\n\t}")
	w("\talways ok {\n\t\trcode = ok\n\t}")
	w("\talways noop {\n\t\trcode = noop\n\t}")
	w("\tpap {\n\t}")
	w("\tchap {\n\t}")
	rest("goblin_mab", "authorize", "mab")
	rest("goblin_post", "post-auth", "post-auth")
	rest("goblin_reject", "post-auth", "reject")
	rest("goblin_acct", "accounting", "accounting")
	if rc.Dot1X {
		rest("goblin_inner", "authorize", "inner")
		w(`	mschap {
		use_mppe = yes
		require_encryption = yes
		require_strong = yes
		with_ntdomain_hack = yes
	}
	eap {
		default_eap_type = peap
		timer_expire = 60
		ignore_unknown_eap_types = no
		cisco_accounting_username_bug = no
		max_sessions = ${max_requests}
		tls-config tls-common {
			private_key_file = ${certdir}/server.key
			certificate_file = ${certdir}/server.pem
			ca_file = ${cadir}/ca.pem
			cipher_list = "DEFAULT"
			cipher_server_preference = yes
			tls_min_version = "1.2"
			tls_max_version = "1.2"
			ecdh_curve = ""
			cache {
				enable = no
			}
			verify {
			}
			ocsp {
				enable = no
			}
		}
		tls {
			tls = tls-common
		}
		peap {
			tls = tls-common
			default_eap_type = mschapv2
			copy_request_to_tunnel = no
			use_tunneled_reply = no
			virtual_server = "goblin-inner"
		}
		mschapv2 {
		}
	}`)
	}
	w("}")
	w("")
	w("instantiate {\n}")
	w("")
	w("policy {\n}")
	w("")

	// the outer server: MAB (no EAP) asks goblind; EAP goes to the eap
	// module. Post-auth asks goblind for the VLAN of every accepted request
	// and tells it about every reject.
	w("server goblin {")
	for _, l := range []struct {
		typ  string
		port int
	}{{"auth", config.RADIUSAuthPort}, {"acct", config.RADIUSAcctPort}} {
		for _, ip := range []string{"ipaddr = *", "ipv6addr = ::"} {
			w("\tlisten {\n\t\ttype = %s\n\t\t%s\n\t\tport = %d\n\t\tlimit {\n\t\t\tmax_connections = 16\n\t\t\tlifetime = 0\n\t\t\tidle_timeout = 30\n\t\t}\n\t}", l.typ, ip, l.port)
		}
	}
	// EAP (802.1X) or else MAB: if/else, because a "return" inside an if
	// only leaves the if
	w("\tauthorize {")
	w("\t\tif (&EAP-Message) {")
	if rc.Dot1X {
		w("\t\t\teap")
	} else {
		w("\t\t\treject")
	}
	w("\t\t}\n\t\telse {")
	if rc.MAB {
		w("%s\t\t\tgoblin_mab", srcAddr)
	} else {
		w("\t\t\treject")
	}
	w("\t\t}\n\t}")
	w("\tauthenticate {")
	if rc.Dot1X {
		w("\t\teap")
	}
	w("\t\tAuth-Type PAP {\n\t\t\tpap\n\t\t}")
	w("\t\tAuth-Type CHAP {\n\t\t\tchap\n\t\t}")
	w("\t}")
	w("\tpreacct {\n\t}")
	w("\taccounting {\n%s\t\tgoblin_acct\n\t\tok\n\t}", srcAddr)
	w("\tsession {\n\t}")
	w("\tpost-auth {")
	if rc.Dot1X {
		// the inner identity (PEAP) reaches goblind through the request
		// and the client certificate's name and serial (EAP-TLS)
		for _, a := range []string{"TLS-Client-Cert-Common-Name", "TLS-Client-Cert-Serial"} {
			w("\t\tif (&session-state:%s) {\n\t\t\tupdate request {\n\t\t\t\t&%s := &session-state:%s\n\t\t\t}\n\t\t}", a, a, a)
		}
		w("\t\tif (&session-state:Tmp-String-1) {\n\t\t\tupdate request {\n\t\t\t\t&Tmp-String-1 := &session-state:Tmp-String-1\n\t\t\t}\n\t\t}")
	}
	w("%s\t\tgoblin_post", srcAddr)
	w("\t\tPost-Auth-Type REJECT {")
	w("%s", strings.TrimSuffix(srcAddr, "\n"))
	if rc.Dot1X {
		// the inner user and why the tunnel refused it
		w("\t\t\tupdate request {\n\t\t\t\t&Tmp-String-1 := &session-state:Tmp-String-1\n\t\t\t\t&Tmp-String-3 := &session-state:Tmp-String-3\n\t\t\t}")
	}
	// a hook that is down must not turn the reject into anything else
	w("\t\t\tif (!&reply:REST-HTTP-Status-Code || &reply:REST-HTTP-Status-Code != 401) {\n\t\t\t\tgoblin_reject {\n\t\t\t\t\tfail = 1\n\t\t\t\t\tnotfound = 1\n\t\t\t\t\treject = 1\n\t\t\t\t}\n\t\t\t}")
	if rc.Dot1X {
		w("\t\t\teap")
	}
	w("\t\t}")
	w("\t}")
	w("}")
	w("")

	if rc.Dot1X {
		// the PEAP tunnel: goblind answers the user's password; mschap checks it
		w("%s", `server goblin-inner {
	authorize {
		goblin_inner
		mschap
		eap {
			ok = return
		}
	}
	authenticate {
		Auth-Type MS-CHAP {
			mschap
		}
		eap
	}
	session {
	}
	post-auth {
		update outer.session-state {
			&Tmp-String-1 := &User-Name
		}
		Post-Auth-Type REJECT {
			update outer.session-state {
				&Tmp-String-1 := &User-Name
				&Tmp-String-3 := "%{Module-Failure-Message}"
			}
		}
	}
}`)
	}
	return []byte(b.String()), nil
}

// srcAddr puts the address the request came from into Tmp-String-2 (which
// switch or access point asked; Disconnect requests go back there).
const srcAddr = "\t\tupdate request {\n\t\t\t&Tmp-String-2 := \"%{%{Packet-Src-IP-Address}:-%{Packet-Src-IPv6-Address}}\"\n\t\t}\n"

// secretOK mirrors the config check: nothing that breaks a quoted string.
func secretOK(s string) bool {
	return s != "" && !strings.ContainsAny(s, "\"'\\` \t\r\n")
}
