// Package netif renders interfaces and VLANs as systemd-networkd files, plus
// the sysctl drop-in that enables IPv4 forwarding.
package netif

import (
	"fmt"
	"net/netip"
	"regexp"
	"slices"
	"strings"

	"github.com/networkgoblinlabs/goblin-gate/internal/config"
	"github.com/networkgoblinlabs/goblin-gate/internal/render"
)

const (
	// Dir holds the generated .network and .netdev files.
	Dir = "/etc/systemd/network"
	// SysctlPath is the sysctl drop-in that turns on IPv4 forwarding.
	SysctlPath = "/etc/sysctl.d/90-goblin.conf"

	header = "# Generated by Goblin Gate — do not edit\n"
)

// NetworkPath returns the .network file for an interface or VLAN name.
// Physical interfaces use prefix 10, VLANs 20.
func NetworkPath(prio int, name string) string {
	return fmt.Sprintf("%s/%d-goblin-%s.network", Dir, prio, name)
}

// NetdevPath returns the .netdev file that creates a VLAN device.
func NetdevPath(name string) string {
	return fmt.Sprintf("%s/20-goblin-%s.netdev", Dir, name)
}

// Renderer renders systemd-networkd and sysctl files.
type Renderer struct{}

// Name implements commit.Renderer.
func (Renderer) Name() string { return "netif" }

// Render returns one .network per interface, a .netdev and .network per VLAN,
// and SysctlPath. Devices are matched by kernel name (VLANs use
// render.VLANDevice, e.g. eth1.20) so names agree with the nft renderer.
// Links without IPv6 keep link-local addressing and RAs off; see ipv6.go.
func (Renderer) Render(cfg *config.Config) (map[string][]byte, error) {
	files, err := build(cfg)
	if err != nil {
		return nil, fmt.Errorf("render netif: %w", err)
	}
	return files, nil
}

// devRe limits device names to what the kernel accepts (IFNAMSIZ-1 = 15
// characters) and keeps them safe inside a unit file.
var devRe = regexp.MustCompile(`^[A-Za-z0-9_.-]{1,15}$`)

// nameRe matches config object names, which become part of file names.
var nameRe = regexp.MustCompile(`^[A-Za-z0-9_.-]{1,63}$`)

// link is the addressing shared by interfaces and VLANs.
type link struct {
	name, dev, mode string
	addr            *netip.Prefix
	gw              *netip.Addr
	mtu             int
	enabled         bool
	wan             bool
	vlans           []string // VLAN devices carried by this link
	v6              *config.IPv6
	v6uplink        string       // delegated: the uplink's device
	raDNS           bool         // announce the box as DNS server in RAs
	route           *linkRouting // multi-WAN: this link carries a gateway
}

func build(cfg *config.Config) (map[string][]byte, error) {
	sysctl := header + "net.ipv4.ip_forward=1\n"
	if cfg.IPv6Enabled() {
		sysctl += "net.ipv6.conf.all.forwarding=1\n"
	}
	files := map[string][]byte{SysctlPath: []byte(sysctl)}
	devs := render.Devices(cfg)
	v6 := newV6Info(cfg, devs)
	seen := map[string]bool{}
	claim := func(kind, name, dev string) error {
		if !nameRe.MatchString(name) {
			return fmt.Errorf("%s %q: invalid name", kind, name)
		}
		if !devRe.MatchString(dev) {
			return fmt.Errorf("%s %q: invalid device name %q", kind, name, dev)
		}
		if seen["n:"+name] {
			return fmt.Errorf("%s %q: duplicate name", kind, name)
		}
		if seen["d:"+dev] {
			return fmt.Errorf("%s %q: device %q is used twice", kind, name, dev)
		}
		seen["n:"+name], seen["d:"+dev] = true, true
		return nil
	}

	phys := make([]*link, 0, len(cfg.Interfaces))
	var vlans []*link
	byName := map[string]*link{}
	for _, ifc := range cfg.Interfaces {
		if err := claim("interface", ifc.Name, ifc.Device); err != nil {
			return nil, err
		}
		l := &link{name: ifc.Name, dev: ifc.Device, mode: ifc.Mode, addr: ifc.Address,
			gw: ifc.Gateway, mtu: ifc.MTU, enabled: ifc.Enabled, wan: ifc.Role == "wan"}
		if err := v6.attach(l, ifc.IPv6); err != nil {
			return nil, fmt.Errorf("interface %q: %w", ifc.Name, err)
		}
		phys = append(phys, l)
		byName[ifc.Name] = l
	}

	for _, v := range cfg.VLANs {
		parent, ok := byName[v.Parent]
		if !ok {
			return nil, fmt.Errorf("vlan %q: unknown parent interface %q", v.Name, v.Parent)
		}
		if v.VLANID < 1 || v.VLANID > 4094 {
			return nil, fmt.Errorf("vlan %q: vlan_id %d out of range 1-4094", v.Name, v.VLANID)
		}
		dev := devs[v.Name]
		if err := claim("vlan", v.Name, dev); err != nil {
			return nil, err
		}
		parent.vlans = append(parent.vlans, dev)
		files[NetdevPath(v.Name)] = []byte(fmt.Sprintf(
			"%s[NetDev]\nName=%s\nKind=vlan\n\n[VLAN]\nId=%d\n", header, dev, v.VLANID))
		l := &link{name: v.Name, dev: dev, mode: v.Mode, addr: v.Address,
			gw: v.Gateway, mtu: v.MTU, enabled: v.Enabled, wan: parent.wan}
		if err := v6.attach(l, v.IPv6); err != nil {
			return nil, fmt.Errorf("vlan %q: %w", v.Name, err)
		}
		vlans = append(vlans, l)
		byName[v.Name] = l
	}

	plan, err := render.Routing(cfg)
	if err != nil {
		return nil, err
	}
	if err := attachRouting(cfg, plan, byName); err != nil {
		return nil, err
	}
	if plan.Enabled {
		files[RulesPath] = rulesFile(plan)
	}
	for _, l := range vlans {
		b, err := network(l)
		if err != nil {
			return nil, fmt.Errorf("vlan %q: %w", l.name, err)
		}
		files[NetworkPath(20, l.name)] = b
	}
	for _, l := range phys {
		b, err := network(l)
		if err != nil {
			return nil, fmt.Errorf("interface %q: %w", l.name, err)
		}
		files[NetworkPath(10, l.name)] = b
	}
	return files, nil
}

// network renders one .network file. A disabled link is kept down but still
// carries its VLAN= lines so the VLAN devices exist.
func network(l *link) ([]byte, error) {
	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "[Match]\nName=%s\n", l.dev)

	if !l.enabled || l.mtu > 0 {
		b.WriteString("\n[Link]\n")
		if l.mtu > 0 {
			fmt.Fprintf(&b, "MTUBytes=%d\n", l.mtu)
		}
		if !l.enabled {
			b.WriteString("ActivationPolicy=down\n")
		}
	}

	b.WriteString("\n[Network]\n")
	v6on := l.enabled && l.v6 != nil && l.v6.Mode != "none" && l.v6.Mode != ""
	dhcp6 := v6on && l.v6.Mode == "dhcp6"
	if l.enabled {
		switch l.mode {
		case "dhcp":
			if dhcp6 {
				b.WriteString("DHCP=yes\n")
			} else {
				b.WriteString("DHCP=ipv4\n")
			}
		case "static":
			if l.addr == nil || !l.addr.Addr().Is4() {
				return nil, fmt.Errorf("static mode needs an IPv4 address")
			}
			fmt.Fprintf(&b, "Address=%s\n", l.addr)
			if l.gw != nil && l.route == nil { // with a gateway: its own table
				if !l.gw.Is4() {
					return nil, fmt.Errorf("gateway %s is not IPv4", l.gw)
				}
				fmt.Fprintf(&b, "Gateway=%s\n", l.gw)
			}
		case "none", "":
			if dhcp6 {
				b.WriteString("DHCP=ipv6\n")
			}
		default:
			return nil, fmt.Errorf("unknown mode %q", l.mode)
		}
		b.WriteString("IPForward=yes\n")
	}
	sections := ""
	if v6on {
		var err error
		if sections, err = ipv6Network(&b, l); err != nil {
			return nil, err
		}
	} else {
		b.WriteString("LinkLocalAddressing=no\nIPv6AcceptRA=no\n")
	}
	for _, dev := range slices.Sorted(slices.Values(l.vlans)) {
		fmt.Fprintf(&b, "VLAN=%s\n", dev)
	}
	b.WriteString(sections)
	if l.route != nil && l.enabled {
		b.WriteString(l.route.sections(l.mode == "dhcp"))
	}
	return []byte(b.String()), nil
}
