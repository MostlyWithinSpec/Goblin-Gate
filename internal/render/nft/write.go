package nft

import (
	"fmt"
	"strings"
)

// write lays out the final ruleset text.
//
// Each table is declared empty, deleted and then defined in full. In one
// `nft -f` transaction this replaces the table atomically, and the empty
// declaration keeps the delete from failing on the first load.
func (r *ruleset) write() []byte {
	var b strings.Builder
	p := func(indent int, format string, args ...any) {
		b.WriteString(strings.Repeat("\t", indent))
		fmt.Fprintf(&b, format, args...)
		b.WriteByte('\n')
	}

	p(0, headerLine)
	p(0, "# Generated by Goblin Gate — do not edit")
	p(0, "")
	p(0, "table inet %s", FilterTable)
	p(0, "delete table inet %s", FilterTable)
	p(0, "")
	p(0, "table inet %s {", FilterTable)

	for _, s := range r.sets {
		p(1, "set %s {", s.name)
		p(2, "type %s", s.typ)
		p(2, "flags interval")
		if s.autoMrg {
			p(2, "auto-merge")
		}
		if s.comment != "" {
			p(2, "comment %s", quote(s.comment))
		}
		if len(s.elements) > 0 {
			p(2, "elements = { %s }", strings.Join(s.elements, ", "))
		}
		p(1, "}")
		p(0, "")
	}

	// temporary blocks (blocks.go), filled by goblind at run time
	for _, s := range []struct{ name, typ string }{{BlockSet4, "ipv4_addr"}, {BlockSet6, "ipv6_addr"}} {
		p(1, "set %s {", s.name)
		p(2, "type %s", s.typ)
		p(2, "flags timeout")
		p(2, "comment %s", quote("temporary blocks"))
		p(1, "}")
		p(0, "")
	}

	for _, c := range r.counters {
		p(1, "counter %s {", c.name)
		if c.comment != "" {
			p(2, "comment %s", quote(c.comment))
		}
		p(1, "}")
	}
	if len(r.counters) > 0 {
		p(0, "")
	}

	// Feeds with block_wan drop their addresses on every WAN interface;
	// per-policy feed drops sit next to the policy's own rules.
	p(1, "chain %s {", blockChain)
	for _, l := range blockRules() {
		p(2, "%s", l)
	}
	p(1, "}")
	p(0, "")

	p(1, "chain threat_feeds {")
	for _, l := range r.feedFwd {
		p(2, "%s", l)
	}
	p(1, "}")
	p(0, "")
	p(1, "chain threat_feeds_input {")
	for _, l := range r.feedIn {
		p(2, "%s", l)
	}
	p(1, "}")
	p(0, "")

	p(1, "chain input {")
	p(2, "type filter hook input priority filter; policy drop;")
	p(2, "jump %s", blockChain)
	p(2, "ct state established,related accept")
	p(2, "ct state invalid drop")
	p(2, `iifname "lo" accept`)
	for _, l := range r.spoof {
		p(2, "%s", l)
	}
	p(2, "jump threat_feeds_input")
	for _, l := range r.input {
		p(2, "%s", l)
	}
	p(1, "}")
	p(0, "")

	p(1, "chain forward {")
	p(2, "type filter hook forward priority filter; policy drop;")
	p(2, "jump %s", blockChain)
	for _, l := range r.ipsQueue {
		p(2, "%s", l)
	}
	p(2, "ct state established,related accept")
	p(2, "ct state invalid drop")
	for _, l := range r.spoof {
		p(2, "%s", l)
	}
	p(2, "jump threat_feeds")
	if r.cfg.UPnP.Enabled {
		p(2, "jump %s comment %s", UPnPForwardChain, quote("upnp mappings (miniupnpd)"))
	}
	for _, l := range r.dnsFwd {
		p(2, "%s", l)
	}
	for _, l := range r.forward {
		p(2, "%s", l)
	}
	p(1, "}")
	p(0, "")

	// The box's own traffic (DNS lookups, DHCP client, NTP, feed downloads)
	// is trusted; only invalid packets are dropped.
	p(1, "chain output {")
	p(2, "type filter hook output priority filter; policy accept;")
	p(2, "ct state invalid drop")
	p(1, "}")
	if r.cfg.UPnP.Enabled {
		// filled by miniupnpd at run time (task 059)
		p(0, "")
		p(1, "chain %s {", UPnPForwardChain)
		p(1, "}")
	}
	if r.route.Enabled {
		// policy routing (task 049, see routing.go): before the routing decision
		p(0, "")
		p(1, "chain route_policies {")
		for _, l := range r.routePol {
			p(2, "%s", l)
		}
		p(1, "}")
		p(0, "")
		p(1, "chain prerouting {")
		p(2, "type filter hook prerouting priority mangle; policy accept;")
		for _, l := range r.routePrerouting() {
			p(2, "%s", l)
		}
		p(1, "}")
	}
	p(0, "}")
	p(0, "")

	p(0, "table ip %s", NATTable)
	p(0, "delete table ip %s", NATTable)
	p(0, "")
	p(0, "table ip %s {", NATTable)
	p(1, "chain dns_redirect {")
	for _, l := range r.dnsRedir {
		p(2, "%s", l)
	}
	p(1, "}")
	p(0, "")
	p(1, "chain prerouting {")
	p(2, "type nat hook prerouting priority dstnat; policy accept;")
	p(2, "jump dns_redirect")
	for _, l := range r.pre {
		p(2, "%s", l)
	}
	p(1, "}")
	p(0, "")
	p(1, "chain postrouting {")
	p(2, "type nat hook postrouting priority srcnat; policy accept;")
	// nat: true translates traffic that leaves through a WAN only: a
	// policy towards "all" interfaces must not masquerade LAN-to-LAN traffic
	// (with multi-WAN also through a VPN-provider tunnel)
	egress := r.wanMatch()
	if r.route.Enabled {
		if ext := r.externalDevs(); len(ext) > 0 {
			egress = devSet(ext)
		}
	}
	if egress != "" {
		p(2, "oifname %s meta mark & 0x%08x == 0x%08x masquerade comment %s", egress, MarkMasquerade, MarkMasquerade, quote("policies with nat enabled"))
	}
	p(1, "}")
	p(0, "}")

	// UPnP / NAT-PMP mappings (task 059): miniupnpd adds its DNAT rules to
	// upnp_dnat at run time. Always deleted, so disabling UPnP drops them;
	// recreated empty when enabled (the applier restarts miniupnpd, which
	// re-adds the mappings from its lease file).
	p(0, "")
	p(0, "table inet %s", UPnPNATTable)
	p(0, "delete table inet %s", UPnPNATTable)
	if r.cfg.UPnP.Enabled {
		p(0, "")
		p(0, "table inet %s {", UPnPNATTable)
		p(1, "chain prerouting {")
		p(2, "type nat hook prerouting priority dstnat; policy accept;")
		p(2, "jump %s", UPnPDNATChain)
		p(1, "}")
		p(0, "")
		p(1, "chain postrouting {")
		p(2, "type nat hook postrouting priority srcnat; policy accept;")
		p(2, "jump %s", UPnPSNATChain)
		p(1, "}")
		p(0, "")
		p(1, "chain %s {", UPnPDNATChain)
		p(1, "}")
		p(0, "")
		p(1, "chain %s {", UPnPSNATChain)
		p(1, "}")
		p(0, "}")
	}
	return []byte(b.String())
}
