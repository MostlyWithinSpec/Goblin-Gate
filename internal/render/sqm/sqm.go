// Package sqm renders smart queue management: CAKE shaping on WAN
// interfaces (upload on the WAN device, download on an ingress IFB device),
// as a shell script of tc commands that the applier runs on every change
// and goblin-sqm.service runs at boot.
package sqm

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"sort"
	"strings"

	"github.com/networkgoblinlabs/goblin-gate/internal/config"
	"github.com/networkgoblinlabs/goblin-gate/internal/render"
)

const (
	// Dir is the renderer's output directory.
	Dir = "/etc/goblingate/sqm/"
	// ScriptPath is the generated script.
	ScriptPath = Dir + "sqm.sh"
)

// Renderer implements commit.Renderer.
type Renderer struct{}

// Name returns "sqm".
func (Renderer) Name() string { return "sqm" }

// Shaper is one WAN device to shape.
type Shaper struct {
	Interface    string
	Device       string
	IFB          string
	DownloadMbit int
	UploadMbit   int
}

// IFBName is the ingress device for dev: "ifb4" + dev when that fits the
// kernel's 15 characters, a hashed name otherwise.
func IFBName(dev string) string {
	if n := "ifb4" + dev; len(n) <= 15 {
		return n
	}
	sum := sha256.Sum256([]byte(dev))
	return "ifb" + hex.EncodeToString(sum[:])[:12]
}

// Plan lists the WAN devices and which of them are shaped.
func Plan(cfg *config.Config) (wanDevices []string, shapers []Shaper) {
	devs := render.Devices(cfg)
	for _, in := range cfg.Interfaces {
		if in.Role != "wan" {
			continue
		}
		dev := devs[in.Name]
		if dev == "" {
			continue
		}
		wanDevices = append(wanDevices, dev)
		if q := in.SQM; in.Enabled && q != nil && q.Enabled && q.DownloadMbit > 0 && q.UploadMbit > 0 {
			shapers = append(shapers, Shaper{Interface: in.Name, Device: dev, IFB: IFBName(dev), DownloadMbit: q.DownloadMbit, UploadMbit: q.UploadMbit})
		}
	}
	sort.Strings(wanDevices)
	return wanDevices, shapers
}

// Render always returns the script: it first removes shaping from every WAN
// device, so turning SQM off (or renaming a device) cleans up.
func (Renderer) Render(cfg *config.Config) (map[string][]byte, error) {
	wans, shapers := Plan(cfg)
	var b strings.Builder
	b.WriteString("#!/bin/sh\n# Generated by Goblin Gate - do not edit. Smart queue (CAKE) on WAN interfaces.\n")
	b.WriteString("# Removes the box's shaping from every WAN device, then adds it where it is on.\n")
	for _, dev := range wans {
		fmt.Fprintf(&b, "tc qdisc del dev %s root 2>/dev/null\n", dev)
		fmt.Fprintf(&b, "tc qdisc del dev %s ingress 2>/dev/null\n", dev)
		fmt.Fprintf(&b, "ip link del %s 2>/dev/null\n", IFBName(dev))
	}
	if len(shapers) > 0 {
		b.WriteString("set -e\n")
	}
	for _, s := range shapers {
		fmt.Fprintf(&b, "# %s: upload %d Mbit/s, download %d Mbit/s\n", s.Interface, s.UploadMbit, s.DownloadMbit)
		// upload: per-host fairness by the LAN address before NAT
		fmt.Fprintf(&b, "tc qdisc replace dev %s root cake bandwidth %dmbit diffserv4 dual-srchost nat\n", s.Device, s.UploadMbit)
		// download: redirect ingress to an IFB device and shape there
		fmt.Fprintf(&b, "ip link add %s type ifb\n", s.IFB)
		fmt.Fprintf(&b, "ip link set %s up\n", s.IFB)
		fmt.Fprintf(&b, "tc qdisc add dev %s handle ffff: ingress\n", s.Device)
		fmt.Fprintf(&b, "tc filter add dev %s parent ffff: protocol all matchall action mirred egress redirect dev %s\n", s.Device, s.IFB)
		fmt.Fprintf(&b, "tc qdisc replace dev %s root cake bandwidth %dmbit diffserv4 dual-dsthost nat wash ingress\n", s.IFB, s.DownloadMbit)
	}
	b.WriteString("exit 0\n")
	return map[string][]byte{ScriptPath: []byte(b.String())}, nil
}
