// Package wireguard renders WireGuard server interfaces (task 036) as
// systemd-networkd .netdev/.network files. The private key is referenced
// with PrivateKeyFile (config.WireGuardKeyDir), never written here.
package wireguard

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/networkgoblinlabs/goblin-gate/internal/config"
)

// Dir is networkd's config directory (the applier's networkd group).
const Dir = "/etc/systemd/network"

// NetdevPath and NetworkPath are an interface's files.
func NetdevPath(name string) string  { return fmt.Sprintf("%s/40-goblin-wg-%s.netdev", Dir, name) }
func NetworkPath(name string) string { return fmt.Sprintf("%s/40-goblin-wg-%s.network", Dir, name) }

// Renderer implements commit.Renderer.
type Renderer struct{}

// Name returns "wireguard".
func (Renderer) Name() string { return "wireguard" }

// Render writes the enabled interfaces; disabled ones get no files, so the
// applier removes them and networkd deletes the device.
func (Renderer) Render(cfg *config.Config) (map[string][]byte, error) {
	files := map[string][]byte{}
	for _, w := range cfg.VPN.WireGuard {
		if !w.Enabled {
			continue
		}
		port := w.ListenPort
		if port == 0 {
			port = config.DefaultWireGuardPort
		}
		var nd strings.Builder
		fmt.Fprintf(&nd, "# Generated by Goblin Gate - do not edit\n[NetDev]\nName=%s\nKind=wireguard\nDescription=WireGuard %s\n\n", w.Name, w.Name)
		fmt.Fprintf(&nd, "[WireGuard]\nPrivateKeyFile=%s\nListenPort=%d\n", filepath.ToSlash(filepath.Join(config.WireGuardKeyDir, w.Name+".key")), port)
		for _, p := range w.Peers {
			allowed := []string{p.Address.String() + "/32"}
			for _, a := range p.AllowedIPs {
				allowed = append(allowed, a.Masked().String())
			}
			fmt.Fprintf(&nd, "\n# %s\n[WireGuardPeer]\nPublicKey=%s\nAllowedIPs=%s\n", p.Name, p.PublicKey, strings.Join(allowed, ","))
			if p.Keepalive > 0 {
				fmt.Fprintf(&nd, "PersistentKeepalive=%d\n", p.Keepalive)
			}
		}
		files[NetdevPath(w.Name)] = []byte(nd.String())

		var nw strings.Builder
		fmt.Fprintf(&nw, "# Generated by Goblin Gate - do not edit\n[Match]\nName=%s\n\n[Network]\nAddress=%s\n", w.Name, w.Address)
		// peers' extra subnets (site-to-site) are routed into the tunnel
		for _, p := range w.Peers {
			for _, a := range p.AllowedIPs {
				fmt.Fprintf(&nw, "\n[Route]\nDestination=%s\n", a.Masked())
			}
		}
		files[NetworkPath(w.Name)] = []byte(nw.String())
	}
	return files, nil
}
