// RPZDir holds one Response Policy Zone file per DNS filter profile.
const RPZDir = "/var/lib/unbound/rpz/"

// ControlSocket is unbound-control's unix socket (remote-control clause);
// the feed syncer reloads zones through it.
const ControlSocket = "/run/unbound.ctl"

// FeedSource returns a feed's last good entries (feeds.Manager.Entries).
type FeedSource interface {
	Entries(name string) []string
}

// safeSearch rewrites search engines to their enforced safe-search hosts.
var safeSearch = [][2]string{
	{"google.com", "forcesafesearch.google.com"},
	{"www.google.com", "forcesafesearch.google.com"},
	{"bing.com", "strict.bing.com"},
	{"www.bing.com", "strict.bing.com"},
	{"duckduckgo.com", "safe.duckduckgo.com"},
	{"www.duckduckgo.com", "safe.duckduckgo.com"},
	{"youtube.com", "restrict.youtube.com"},
	{"www.youtube.com", "restrict.youtube.com"},
	{"m.youtube.com", "restrict.youtube.com"},
	{"youtubei.googleapis.com", "restrict.youtube.com"},
	{"youtube.googleapis.com", "restrict.youtube.com"},
	{"www.youtube-nocookie.com", "restrict.youtube.com"},
}

// ZoneName is the RPZ zone of a profile, e.g. "kids.rpz.goblin.".
func ZoneName(profile string) string { return sanitize(profile) + ".rpz.goblin." }

// ZonePath is where a profile's zone file is written.
func ZonePath(profile string) string { return RPZDir + sanitize(profile) + ".zone" }

// Tag is the Unbound tag that selects a profile's zone for its subnets.
func Tag(profile string) string { return "gg_" + sanitize(profile) }

func sanitize(s string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(s) {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '_' {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	return b.String()
}

// ZoneFile renders a profile's RPZ zone. Every blocked or allowed name also
// covers its subdomains (a "*." record). allow_domains become rpz-passthru
// and win over the block lists; blocked names answer NXDOMAIN (CNAME .) or,
// with action blockpage, blockAddr. Safe search rewrites the search
// engines to their safe hosts. feeds may be nil (no feed entries yet).
func ZoneFile(p config.DNSFilterProfile, feeds FeedSource, blockAddr string) []byte {
	allow := map[string]bool{}
	for _, d := range p.AllowDomains {
		allow[normDomain(d)] = true
	}
	block := map[string]bool{}
	add := func(d string) {
		if d = normDomain(d); d != "" && !allow[d] {
			block[d] = true
		}
	}
	for _, d := range p.BlockDomains {
		add(d)
	}
	if feeds != nil {
		for _, f := range p.BlockFeeds {
			for _, d := range feeds.Entries(f) {
				add(d)
			}
		}
	}
	var rewrite []string
	if p.SafeSearch {
		for _, s := range safeSearch {
			if !allow[s[0]] && !block[s[0]] {
				rewrite = append(rewrite, fmt.Sprintf("%s CNAME %s.", s[0], s[1]))
			}
		}
	}

	answer := "CNAME ."
	if p.Action == "blockpage" && blockAddr != "" {
		answer = "A " + blockAddr
	}
	var b strings.Builder
	fmt.Fprintf(&b, "; Generated by Goblin Gate for DNS filter profile %q - do not edit\n", p.Name)
	fmt.Fprintf(&b, "$ORIGIN %s\n$TTL 300\n", ZoneName(p.Name))
	b.WriteString("@ SOA localhost. root.localhost. 1 3600 600 86400 300\n")
	b.WriteString("@ NS localhost.\n")
	for _, d := range sortedKeys(allow) {
		fmt.Fprintf(&b, "%s CNAME rpz-passthru.\n*.%s CNAME rpz-passthru.\n", d, d)
	}
	for _, r := range rewrite {
		b.WriteString(r + "\n")
	}
	for _, d := range sortedKeys(block) {
		fmt.Fprintf(&b, "%s %s\n*.%s %s\n", d, answer, d, answer)
	}
	return []byte(b.String())
}

// normDomain lowercases a name and strips "*." and the trailing dot; it
// returns "" for names that cannot be written into a zone.
func normDomain(d string) string {
	d = strings.TrimSuffix(strings.TrimPrefix(strings.ToLower(strings.TrimSpace(d)), "*."), ".")
	if d == "" || strings.ContainsAny(d, " \t;()\"\\$@") || !strings.Contains(d, ".") {
		return ""
	}
	return d
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// Zone is a DNS filter profile in use: the subnets it applies to and its
// block page address (the box's address on the first of them). A profile
// nobody uses gets no rpz clause: a clause without tags would filter every
// client.
type Zone struct {
	Profile   config.DNSFilterProfile
	Subnets   []string
	BlockAddr string
}

// Zones lists the profiles in use, sorted by name.
func Zones(cfg *config.Config) []Zone {
	byName := map[string]*Zone{}
	var order []string
	for _, a := range render.DNSFilterAssignments(cfg) {
		z, ok := byName[a.Profile]
		if !ok {
			for _, p := range cfg.Profiles.DNSFilter {
				if p.Name == a.Profile {
					z = &Zone{Profile: p, BlockAddr: a.Address.Addr().String()}
				}
			}
			byName[a.Profile] = z
			order = append(order, a.Profile)
		}
		z.Subnets = append(z.Subnets, a.Address.Masked().String())
	}
	sort.Strings(order)
	out := make([]Zone, 0, len(order))
	for _, name := range order {
		out = append(out, *byName[name])
	}
	return out
}

// ZoneFiles renders every used profile's zone, keyed by ZonePath.
func ZoneFiles(cfg *config.Config, feeds FeedSource) map[string][]byte {
	out := map[string][]byte{}
	for _, z := range Zones(cfg) {
		out[ZonePath(z.Profile.Name)] = ZoneFile(z.Profile, feeds, z.BlockAddr)
	}
	return out
}
