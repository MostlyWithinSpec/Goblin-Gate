// Package unbound renders the Unbound DNS resolver configuration.
package unbound

import (
	"fmt"
	"net/netip"
	"sort"
	"strings"

	"github.com/networkgoblinlabs/goblin-gate/internal/config"
)

// Path is where the Unbound config is written.
const Path = "/etc/unbound/unbound.conf.d/goblin.conf"

// Renderer implements commit.Renderer for Unbound DNS resolver. Feeds
// supplies the domain feed entries for DNS filter zones; nil renders the
// zones without feed entries (the feed syncer fills them in later).
type Renderer struct {
	Feeds FeedSource
}

// Name returns "unbound".
func (Renderer) Name() string { return "unbound" }

// listenPrefixes returns the address of every enabled non-wan interface and
// VLAN with a static address: the same links the nft renderer opens port 53
// on. A VLAN on a wan parent is wan.
func listenPrefixes(cfg *config.Config) []netip.Prefix {
	var out []netip.Prefix
	wan := map[string]bool{}
	for _, ifc := range cfg.Interfaces {
		wan[ifc.Name] = ifc.Role == "wan"
		if ifc.Enabled && ifc.Role != "wan" && ifc.Address != nil {
			out = append(out, *ifc.Address)
		}
	}
	for _, v := range cfg.VLANs {
		if v.Enabled && !wan[v.Parent] && v.Address != nil {
			out = append(out, *v.Address)
		}
	}
	// WireGuard clients use the box's resolver too (task 036)
	for _, w := range cfg.VPN.WireGuard {
		if w.Enabled && w.Address.IsValid() {
			out = append(out, w.Address)
		}
	}
	return out
}

// Render returns the Unbound configuration file keyed by Path.
// It never touches the OS.
//
// DNSSEC: Debian's unbound package already sets auto-trust-anchor-file in
// unbound.conf.d/root-auto-trust-anchor-file.conf (and creates root.key on
// service start), so this file only switches validation on or off with
// module-config; naming the anchor here again would fail unbound-checkconf
// before the first start.
func (r Renderer) Render(cfg *config.Config) (map[string][]byte, error) {
	zones := Zones(cfg)
	var b strings.Builder
	b.WriteString("# Generated by Goblin Gate — do not edit\n")
	b.WriteString("server:\n")

	listen := listenPrefixes(cfg)
	b.WriteString("  interface: 127.0.0.1\n")
	for _, p := range listen {
		fmt.Fprintf(&b, "  interface: %s\n", p.Addr())
	}
	// Interfaces may come up after unbound (or be renumbered by a commit).
	b.WriteString("  ip-freebind: yes\n")
	b.WriteString("  do-ip6: no\n")

	b.WriteString("  access-control: 127.0.0.0/8 allow\n")
	for _, p := range listen {
		fmt.Fprintf(&b, "  access-control: %s allow\n", p.Masked())
	}
	b.WriteString("  access-control: 0.0.0.0/0 refuse\n")

	b.WriteString("  hide-identity: yes\n")
	b.WriteString("  hide-version: yes\n")
	b.WriteString("  qname-minimisation: yes\n")
	b.WriteString("  prefetch: yes\n")
	// respip runs the DNS filter's response policy zones.
	modules := "iterator"
	if cfg.DNS.DNSSEC {
		modules = "validator " + modules
	}
	if len(zones) > 0 {
		modules = "respip " + modules
	}
	fmt.Fprintf(&b, "  module-config: \"%s\"\n", modules)

	// DNS filter: one tag per used profile, given to the subnets the profile
	// applies to (render.DNSFilterAssignments); each zone below only answers
	// for its tag. The tagged netblocks equal access-control lines above.
	if len(zones) > 0 {
		var tags []string
		for _, z := range zones {
			tags = append(tags, Tag(z.Profile.Name))
		}
		fmt.Fprintf(&b, "  define-tag: \"%s\"\n", strings.Join(tags, " "))
		for _, z := range zones {
			for _, sn := range z.Subnets {
				fmt.Fprintf(&b, "  access-control-tag: %s \"%s\"\n", sn, Tag(z.Profile.Name))
			}
		}
	}

	// Local records and DHCP static lease hostnames.
	var records []string
	for name, ip := range cfg.DNS.LocalRecords {
		records = append(records, fmt.Sprintf("  local-data: \"%s A %s\"\n", name, ip))
	}
	for _, d := range cfg.DHCP {
		for _, l := range d.StaticLeases {
			if l.Hostname == "" {
				continue
			}
			host := l.Hostname
			if cfg.System.Domain != "" {
				host += "." + cfg.System.Domain
			}
			records = append(records, fmt.Sprintf("  local-data: \"%s A %s\"\n", host, l.IP))
		}
	}
	sort.Strings(records)
	for _, r := range records {
		b.WriteString(r)
	}

	if len(cfg.DNS.Forwarders) > 0 {
		b.WriteString("\nforward-zone:\n")
		b.WriteString("  name: \".\"\n")
		for _, f := range cfg.DNS.Forwarders {
			fmt.Fprintf(&b, "  forward-addr: %s\n", f)
		}
	}

	for _, z := range zones {
		fmt.Fprintf(&b, "\nrpz:\n  name: \"%s\"\n  zonefile: \"%s\"\n  tags: \"%s\"\n  rpz-log: yes\n  rpz-log-name: \"%s\"\n",
			ZoneName(z.Profile.Name), ZonePath(z.Profile.Name), Tag(z.Profile.Name), z.Profile.Name)
	}

	// unbound-control over a root-only unix socket: the feed syncer reloads
	// RPZ zones with it when a domain feed changes.
	fmt.Fprintf(&b, "\nremote-control:\n  control-enable: yes\n  control-interface: %s\n", ControlSocket)

	files := ZoneFiles(cfg, r.Feeds)
	files[Path] = []byte(b.String())
	return files, nil
}
