// Package nic renders network card offload settings (config
// interfaces[].offloads) as a shell script of ethtool commands that the
// applier runs on every change and goblin-nic.service runs at boot.
package nic

import (
	"fmt"
	"sort"
	"strings"

	"github.com/networkgoblinlabs/goblin-gate/internal/config"
	"github.com/networkgoblinlabs/goblin-gate/internal/render"
)

const (
	// Dir is the renderer's output directory.
	Dir = "/etc/goblingate/nic/"
	// ScriptPath is the generated script.
	ScriptPath = Dir + "offloads.sh"
)

// Renderer implements commit.Renderer.
type Renderer struct{}

// Name returns "nic".
func (Renderer) Name() string { return "nic" }

// Features maps an Offloads setting to its ethtool -K name.
func Features(o *config.Offloads) map[string]bool {
	out := map[string]bool{}
	if o == nil {
		return out
	}
	for name, v := range map[string]*bool{"gro": o.GRO, "gso": o.GSO, "tso": o.TSO, "lro": o.LRO, "rx": o.RXChecksum, "tx": o.TXChecksum} {
		if v != nil {
			out[name] = *v
		}
	}
	return out
}

// Render writes one ethtool -K line per enabled interface with overrides.
// A setting the driver does not allow to change only logs a warning: the
// script never fails a commit.
func (Renderer) Render(cfg *config.Config) (map[string][]byte, error) {
	devs := render.Devices(cfg)
	var b strings.Builder
	b.WriteString("#!/bin/sh\n# Generated by Goblin Gate - do not edit. Network card offloads (ethtool -K).\n")
	for _, in := range cfg.Interfaces {
		f := Features(in.Offloads)
		dev := devs[in.Name]
		if !in.Enabled || dev == "" || len(f) == 0 {
			continue
		}
		names := make([]string, 0, len(f))
		for n := range f {
			names = append(names, n)
		}
		sort.Strings(names)
		args := make([]string, 0, len(names))
		for _, n := range names {
			state := "off"
			if f[n] {
				state = "on"
			}
			args = append(args, n+" "+state)
		}
		fmt.Fprintf(&b, "# %s\nethtool -K %s %s || echo \"goblin: could not set the offloads of %s\" >&2\n", in.Name, dev, strings.Join(args, " "), dev)
	}
	b.WriteString("exit 0\n")
	return map[string][]byte{ScriptPath: []byte(b.String())}, nil
}
